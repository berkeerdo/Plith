#!/usr/bin/env node
// Praxvon structure check: fails when a hand-written file passes its line limit,
// when a file already over the limit (listed in the baseline) grows, or when an
// em dash (U+2014) is added to code or docs.
//
// Usage (from the repo root):
//   node scripts/structure-check.mjs                    check, exit 1 on violations
//   node scripts/structure-check.mjs --update-baseline  freeze today's oversized files
//
// Optional structure.config.json at the repo root:
//   { "limits": { "source": 500, "test": 800, "entry": 150 },
//     "ignore": ["^vendor/", "\\.min\\.js$"],
//     "baseline": "structure-baseline.json" }
//
// Lines are non-blank lines, comments included: lint `max-lines` must use
// skipBlankLines: true, skipComments: false, or the two counts disagree.
// Copied component kits are skipped only where their marker file sits in an
// ancestor folder: `components/pui/` with `pui.json`, `components/ui/` with
// shadcn's `components.json`. Without the marker the folder is hand-written
// and checked. "ignore" adds patterns of its own.
//
// --update-baseline creates the baseline on the first run. Once it exists, the
// flag only lowers or drops entries: a new oversized file or a new em dash is
// refused (exit 1), so re-running it can never legalize growth.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const DEFAULT_LIMITS = { source: 500, test: 800, entry: 150 };

const CODE_EXT = /\.(ts|tsx|js|jsx|mjs|cjs|vue|svelte|astro|go|cs|rs|py|dart|swift|kt|php)$/;
const DOC_EXT = /\.(md|mdx|txt)$/;
const EM_DASH = /\u2014/g;
const TEST = /(\.(test|spec)\.[cm]?[jt]sx?$|_test\.go$|Tests?\.cs$|(^|\/)test_[^/]*\.py$|_test\.py$|(^|\/)(__tests__|tests?|e2e)\/)/;
const GENERATED_PATH = /(\.gen\.|\.generated\.|\.g\.cs$|\.g\.i\.cs$|\.designer\.cs$|\.d\.ts$|ModelSnapshot\.cs$|(^|\/)(migrations|generated|__generated__|drizzle)\/)/i;
// Copied component kits: their size is the upstream's, split there, not here.
const KIT_MARKERS = { pui: 'pui.json', ui: 'components.json' };
const KIT_PATH = /^(.*?\/)?components\/(pui|ui)\//;
const GENERATED_HEADER = /(Code generated .* DO NOT EDIT|@generated|<auto-generated)/i;

/** Thin entry files: route/page/screen files and code-behind, which should only compose. */
function isEntry(p) {
  if (/\.xaml\.cs$/.test(p)) return true;
  if (/(^|\/)cmd\/[^/]+\/main\.go$/.test(p) || /(^|\/)src(-tauri)?\/main\.rs$/.test(p)) return true;
  if (/(^|\/)(page|layout|template|loading|error|not-found|route)\.[jt]sx?$/.test(p)) return true;
  const inRouteDir = p.match(/(^|\/)(app|routes)\/(.*)$/);
  if (inRouteDir && /\.[jt]sx$/.test(p)) {
    // `_x` (Next private) and `-x` (TanStack) folders hold colocated non-route code.
    return !inRouteDir[3].split('/').slice(0, -1).some((seg) => /^[_-]/.test(seg));
  }
  return false;
}

export function classify(p) {
  if (TEST.test(p)) return 'test';
  if (isEntry(p)) return 'entry';
  return 'source';
}

export function isGenerated(p, text) {
  if (GENERATED_PATH.test(p)) return true;
  return GENERATED_HEADER.test(text.split('\n', 5).join('\n'));
}

export function countLines(text) {
  return text.split(/\r?\n/).filter((l) => l.trim() !== '').length;
}

export function countEmDashes(text) {
  return (text.match(EM_DASH) ?? []).length;
}

function checkLines(p, lines, frozenLines, limits, violations, ratchet) {
  const kind = classify(p);
  const limit = limits[kind];
  if (frozenLines !== undefined) {
    if (lines > frozenLines) violations.push(`${p}: baselined file grew ${frozenLines} -> ${lines} (${kind} limit ${limit})`);
    else if (lines <= limit) ratchet.push(`${p}: now ${lines}, under the limit; drop it from the baseline`);
    else if (lines < frozenLines) ratchet.push(`${p}: shrank ${frozenLines} -> ${lines}; lower the baseline`);
  } else if (lines > limit) {
    violations.push(`${p}: ${lines} lines, over the ${kind} limit ${limit}`);
  }
}

/**
 * @param files    [{ path, lines, emDashes }] hand-written code and doc files
 * @param baseline { lines: { path: n }, emDashes: { path: n } } frozen legacy state
 * @returns { violations: string[], ratchet: string[] }
 */
export function evaluate(files, baseline, limits) {
  const violations = [];
  const ratchet = [];
  const frozenLines = baseline.lines ?? {};
  const frozenDashes = baseline.emDashes ?? {};
  for (const { path: p, lines, emDashes = 0 } of files) {
    if (CODE_EXT.test(p)) checkLines(p, lines, frozenLines[p], limits, violations, ratchet);
    const allowed = frozenDashes[p] ?? 0;
    if (emDashes > allowed) violations.push(`${p}: ${emDashes - allowed} new em dash (U+2014); use a comma, colon or new sentence`);
    else if (emDashes < allowed) ratchet.push(`${p}: em dashes ${allowed} -> ${emDashes}; lower the baseline`);
  }
  return { violations, ratchet };
}

/** True when `p` sits in a kit folder whose marker exists in one of its ancestor folders. */
function isKitCopy(p, hasMarker) {
  const m = p.match(KIT_PATH);
  if (!m) return false;
  const dirs = (m[1] ?? '').split('/').filter(Boolean);
  for (let i = dirs.length; i >= 0; i--) {
    if (hasMarker(dirs.slice(0, i).join('/'), KIT_MARKERS[m[2]])) return true;
  }
  return false;
}

/**
 * @param extra     project "ignore" patterns
 * @param hasMarker (dir, fileName) => boolean, dir relative to the repo root ('' = root)
 */
export function isIgnored(p, extra, hasMarker = () => false) {
  return isKitCopy(p, hasMarker) || extra.some((re) => re.test(p));
}

/**
 * @param old null on the first run (no baseline file yet)
 * @returns { baseline, refused: string[] } refused = new oversized files and new
 *          em dashes that an existing baseline will not admit
 */
export function nextBaseline(files, old, limits) {
  const refused = [];
  const next = { lines: {}, emDashes: {} };
  const freeze = (prev, now, label) => {
    if (old === null) return now;
    if (prev === undefined) {
      refused.push(label);
      return undefined;
    }
    // Never raise a frozen value: a grown file must be split, not re-frozen.
    return Math.min(prev, now);
  };
  for (const f of files) {
    if (CODE_EXT.test(f.path) && f.lines > limits[classify(f.path)]) {
      const v = freeze(old?.lines?.[f.path], f.lines, `${f.path}: ${f.lines} lines, new oversized file`);
      if (v !== undefined) next.lines[f.path] = v;
    }
    const dashes = f.emDashes ?? 0;
    if (dashes > 0) {
      const v = freeze(old?.emDashes?.[f.path], dashes, `${f.path}: ${dashes} new em dash`);
      if (v !== undefined) next.emDashes[f.path] = v;
    }
  }
  return { baseline: next, refused };
}

function loadJson(file, fallback) {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return fallback; }
}

/** Tracked and untracked, non-ignored files; null outside a git work tree (e.g. a CI copy). */
function listFiles(root) {
  try {
    return execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'],
      { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    return null;
  }
}

function collect(root, ignore, out) {
  const markers = new Map();
  const hasMarker = (dir, name) => {
    const key = path.join(dir, name);
    if (!markers.has(key)) markers.set(key, fs.existsSync(path.join(root, key)));
    return markers.get(key);
  };
  const files = [];
  for (const rel of out.split('\0')) {
    if (!rel || !(CODE_EXT.test(rel) || DOC_EXT.test(rel)) || isIgnored(rel, ignore, hasMarker)) continue;
    let text;
    try { text = fs.readFileSync(path.join(root, rel), 'utf8'); } catch { continue; }
    if (isGenerated(rel, text)) continue;
    files.push({ path: rel, lines: countLines(text), emDashes: countEmDashes(text) });
  }
  return files;
}

function main() {
  const root = process.cwd();
  const config = loadJson(path.join(root, 'structure.config.json'), {});
  const limits = { ...DEFAULT_LIMITS, ...config.limits };
  const ignore = (config.ignore ?? []).map((s) => new RegExp(s));
  const baselinePath = path.join(root, config.baseline ?? 'structure-baseline.json');
  const listed = listFiles(root);
  if (listed === null) {
    // A copied tree (no .git) cannot tell ignored from tracked files: say so, never pass silently.
    console.log('structure-check: SKIPPED, not a git work tree; run it in a checkout before merging');
    return;
  }
  const files = collect(root, ignore, listed);

  if (process.argv.includes('--update-baseline')) {
    const old = fs.existsSync(baselinePath) ? loadJson(baselinePath, {}) : null;
    const { baseline, refused } = nextBaseline(files, old, limits);
    const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
    fs.writeFileSync(baselinePath, JSON.stringify({ lines: sorted(baseline.lines), emDashes: sorted(baseline.emDashes) }, null, 2) + '\n');
    console.log(`baseline: ${Object.keys(baseline.lines).length} oversized files, `
      + `${Object.keys(baseline.emDashes).length} files with em dashes frozen in ${path.basename(baselinePath)}`);
    for (const r of refused) console.log(`REFUSED  ${r}`);
    if (refused.length) {
      console.log('A baseline only shrinks: split the file or rewrite the em dash.');
      process.exit(1);
    }
    return;
  }

  const { violations, ratchet } = evaluate(files, loadJson(baselinePath, {}), limits);
  for (const r of ratchet) console.log(`ratchet  ${r}`);
  for (const v of violations) console.log(`FAIL     ${v}`);
  console.log(`structure-check: ${files.length} files, ${violations.length} violations`);
  if (violations.length) {
    console.log('Fix: split oversized files along their seams, rewrite new em dashes '
      + '(skill praxvon-structure). Never raise the baseline.');
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
